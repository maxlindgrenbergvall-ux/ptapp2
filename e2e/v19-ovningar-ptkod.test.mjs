// E2E för v19 i demoläge: egna övningar (klientens eget pass och PT:ns
// passbyggare), PT:ns knapp "Bjud in existerande klient", klientens
// kodinmatning under Inställningar, /ref/EX-… och serviceavgiften 5 % / 10 % i kassan.
//   npm run build && npm start   (utan Supabase-variabler)
//   BASE_URL=http://localhost:3000 node e2e/v19-ovningar-ptkod.test.mjs [skärmdumpsmapp]
import { chromium } from "playwright"
import fs from "node:fs"

const out = process.argv[2] ?? "e2e/screenshots"
fs.mkdirSync(out, { recursive: true })
const base = process.env.BASE_URL ?? "http://localhost:3000"
const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {})
const errors = []
const ok = (m) => console.log("ok  ", m)
const fail = (m) => {
  console.log("FAIL", m)
  process.exitCode = 1
}
const check = (c, m) => (c ? ok(m) : fail(m))
const norm = (s) => s.replace(/\s+/g, " ").trim()

const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, permissions: ["clipboard-read", "clipboard-write"] })
const p = await ctx.newPage()
p.on("pageerror", (e) => errors.push(`${p.url()} pageerror: ${e.message}`))
p.on("console", (m) => m.type() === "error" && !/Failed to load resource/.test(m.text()) && errors.push(`${p.url()} console: ${m.text()}`))
const demo = () => p.evaluate(() => JSON.parse(localStorage["coavira:demo:v5"]).data)

// ------------------------------------------- 1. Klient: egen övning i eget pass ---
await p.goto(base + "/klient")
await p.click("button:has-text('Logga eget pass')")
await p.fill("#own-search", "Zercher")
await p.waitForSelector("text=Ingen övning hittades.")
ok("övningen saknas i biblioteket")
await p.click("button:has-text('Lägg till egen övning')")
const dlg = p.locator("[data-testid=custom-exercise-dialog]")
await dlg.waitFor()
check((await p.inputValue("#cx-name")) === "Zercher", "namnet förifylls med det klienten sökte på")
await p.fill("#cx-name", "Zercher-utfall med paus")
await p.fill("#cx-weight", "45")
await dlg.locator("role=radio[name=lbs]").click()
await p.fill("#cx-sets", "4")
await p.fill("#cx-reps", "8")
await p.screenshot({ path: `${out}/v19-egen-ovning.png` })
await dlg.locator("button:has-text('Spara och lägg i passet')").click()
await dlg.waitFor({ state: "detached" })
const items = p.locator("[aria-label='Övningar i passet'] li")
await items.first().waitFor()
check((await items.first().innerText()).includes("Zercher-utfall med paus"), "den egna övningen ligger direkt i passet")
check((await items.first().locator("[aria-label=Set]").inputValue()) === "4", "med sina set (4)")
check((await items.first().locator("[aria-label=Reps]").inputValue()) === "8", "och reps (8)")
check((await items.first().locator("[aria-label=Kg]").inputValue()).replace(",", ".") === "20.5", "45 lbs blir 20,5 kg i passet")
const d1 = await demo()
const mine = d1.exercises.find((e) => e.name === "Zercher-utfall med paus")
check(mine?.custom?.ownerId === "c1" && mine.custom.defaultWeight === 45 && mine.custom.weightUnit === "lbs", "övningen sparas kopplad till användaren (45 lbs)")
check(/^cx-/.test(mine?.id ?? ""), "egna övningar har egna id:n (cx-…)")

// Samma namn igen avvisas; övningen syns i sökningen med märket Egen.
await p.fill("#own-search", "zercher")
check(await p.locator("[aria-label='Övningar att välja']").count() === 1, "sökningen fungerar")
await p.click("button:has-text('Lägg till egen övning')")
await p.fill("#cx-name", "zercher-utfall med paus")
await dlg.locator("button:has-text('Spara och lägg i passet')").click()
await p.waitForSelector("text=Du har redan en egen övning som heter")
ok("samma namn två gånger avvisas")
await dlg.locator("button:has-text('Avbryt')").click()
await p.click("button:has-text('Starta passet')")
await p.waitForURL(/\/klient\/pass\//)
await p.waitForSelector("text=Zercher-utfall med paus")
ok("övningen visas i träningspassvyn")
await p.screenshot({ path: `${out}/v19-passvy.png`, fullPage: true })

// ------------------------------------- 2. Klient: PT:ns kod under Inställningar ---
await p.goto(base + "/klient/installningar")
const card = p.locator("[data-testid=pt-invite-redeem]")
await card.waitFor()
check((await card.innerText()).includes("Har du en inbjudningskod från din PT?"), "fältet finns under Inställningar")
check((await card.innerText()).includes("Befintlig klient hos Elin"), "Sara är redan befintlig klient hos Elin")
await card.locator("input").fill("EX-ZZZZZZ")
await card.locator("button:has-text('Koppla')").click()
await card.locator("text=Koden finns inte eller har redan använts").waitFor()
ok("okänd kod avvisas")
await card.locator("input").fill("ex davk42")
check((await card.locator("input").inputValue()) === "EX-DAVK42", "koden formateras medan klienten skriver")
await card.locator("button:has-text('Koppla')").click()
await p.waitForSelector("text=Du är kopplad till David Ek")
await card.locator("text=Befintlig klient hos David Ek").waitFor()
const d2 = await demo()
const rel = d2.relationships.find((r) => r.clientId === "c1" && r.trainerId === "t6")
check(rel?.acquisition === "EXISTING_CLIENT" && rel.status === "active", "klienten kopplas direkt till PT:n som EXISTING_CLIENT")
check(d2.ptInvites.find((i) => i.code === "EX-DAVK42")?.isUsed === true, "koden förbrukas")
await card.locator("input").fill("EX-DAVK42")
await card.locator("button:has-text('Koppla')").click()
await card.locator("text=Koden finns inte eller har redan använts").waitFor()
ok("en kod kan bara användas en gång")
await p.screenshot({ path: `${out}/v19-klient-kod.png`, fullPage: true })

// Ahmed: Sara har köpt hos honom i appen → plattformsklient; en kod kan inte sänka avgiften i efterhand.
await p.evaluate(() => {
  const s = JSON.parse(localStorage["coavira:demo:v5"])
  s.data.ptInvites.push({ id: "pti-t2", trainerId: "t2", code: "EX-AHMD22", isUsed: false, expiresAt: new Date(Date.now() + 86400000).toISOString(), createdAt: new Date().toISOString() })
  localStorage["coavira:demo:v5"] = JSON.stringify(s)
})
await p.reload()
await card.waitFor()
await card.locator("input").fill("EX-AHMD22")
await card.locator("button:has-text('Koppla')").click()
await card.locator("text=Du har redan köpt hos PT:n via Coavira").waitFor()
ok("plattformsklient med köp kan inte bli befintlig klient")

// --------------------------------------------------- 3. Kassan: 5 % eller 10 % ---
// Köpdialogen hos Elin (befintlig klient) och Ahmed (plattformsklient).
await p.goto(base + "/klient/hitta/t1")
await p.click('button[aria-label="Välj Enstaka pass"]')
const upsellNo = p.locator("button:has-text('Nej tack')")
if (await upsellNo.isVisible().catch(() => false)) await upsellNo.click()
await p.waitForSelector("[data-testid=checkout-total-fee-label]")
check(norm(await p.locator("[data-testid=checkout-total-fee-label]").innerText()) === "Serviceavgift (5 %)", "befintlig klient (Elin): 5 % i kassan")
check(await p.locator("[data-testid=checkout-total-existing]").isVisible(), "kassan förklarar den lägre avgiften")
const sub = Number((await p.locator("[data-testid=checkout-total-subtotal]").innerText()).replace(/\D/g, ""))
const fee = Number((await p.locator("[data-testid=checkout-total-fee]").innerText()).replace(/\D/g, ""))
check(fee === Math.floor((sub * 5 + 50) / 100), `5 % av ${sub} kr = ${fee} kr`)
await p.screenshot({ path: `${out}/v19-kassa-5.png` })
await p.keyboard.press("Escape")

await p.goto(base + "/klient/hitta/t2")
await p.locator('button[aria-label^="Välj "]').first().click()
const no2 = p.locator("button:has-text('Nej tack')")
if (await no2.isVisible().catch(() => false)) await no2.click()
await p.waitForSelector("[data-testid=checkout-total-fee-label]")
check(norm(await p.locator("[data-testid=checkout-total-fee-label]").innerText()) === "Serviceavgift (10 %)", "plattformsklient (Ahmed): 10 % i kassan")
check((await p.locator("[data-testid=checkout-total-existing]").count()) === 0, "ingen rabattrad för plattformsklienter")
await p.keyboard.press("Escape")

// Varukorgen: David (nu befintlig klient) 5 %.
await p.goto(base + "/klient/hitta/t6")
await p.waitForSelector("text=David Ek")
await p.locator('button[aria-label^="Lägg "][aria-label$=" i varukorgen"]').first().click()
await p.waitForSelector("text=ligger i varukorgen")
await p.click('button[aria-label^="Varukorg"]')
const group = p.locator("[data-testid=cart] section").filter({ hasText: "David" })
await group.waitFor()
check(norm(await group.locator("[data-testid=cart-total-fee-label]").innerText()) === "Serviceavgift (5 %)", "varukorgen: 5 % hos PT:n klienten kopplats till med kod")
const cSub = Number((await group.locator("[data-testid=cart-total-subtotal]").innerText()).replace(/\D/g, ""))
const cTot = Number((await group.locator("[data-testid=cart-total]").innerText()).replace(/\D/g, ""))
check(cTot === cSub + Math.floor((cSub * 5 + 50) / 100), `totalt = deltotal + 5 % (${cTot} kr)`)
await p.screenshot({ path: `${out}/v19-varukorg-5.png` })
await p.keyboard.press("Escape")

// --------------------------------------------- 4. PT: Bjud in existerande klient ---
await p.goto(base + "/pt")
await p.waitForSelector("text=Klienter")
const sara = p.locator("tr", { hasText: "Sara" }).first()
check(await sara.locator("text=Befintlig · 5 %").isVisible(), "klientöversikten märker befintliga klienter")
await p.locator("button:has-text('Bjud in existerande klient')").first().click()
const inv = p.locator("[data-testid=pt-invite-dialog]")
await inv.waitFor()
check((await inv.innerText()).includes("5 % serviceavgift i stället för 10 %"), "dialogen förklarar avgiften")
await p.fill("#invite-label", "Anna S.")
await inv.locator("button:has-text('Skapa kod')").click()
const codeEl = inv.locator("[data-testid=pt-invite-code]")
await codeEl.waitFor()
const code = (await codeEl.innerText()).trim()
check(/^EX-[A-HJ-NP-Z2-9]{6}$/.test(code), `unik engångskod skapas (${code})`)
check((await inv.locator("[data-testid=pt-invite-link]").innerText()).trim() === `https://coavira.fit/ref/${code}`, "med länk")
await inv.locator("button[aria-label='Kopiera koden']").click()
check((await p.evaluate(() => navigator.clipboard.readText())) === code, "koden kopieras")
await p.screenshot({ path: `${out}/v19-pt-kod.png` })
await inv.locator("button:has-text('Klar')").click()
const list = p.locator("[data-testid=pt-invites-list]")
await list.locator(`text=${code}`).waitFor()
check((await list.innerText()).includes("Anna S."), "koden listas med PT:ns anteckning")
check((await list.innerText()).includes("Använd av Sara"), "använda koder visar vem som använde dem")
await list.locator(`button[aria-label='Ta bort koden ${code}']`).click()
await list.locator(`text=${code}`).waitFor({ state: "detached" })
ok("PT:n tar bort en oanvänd kod")
check(!(await demo()).ptInvites.some((i) => i.code === code), "borttagen ur datan")

// ----------------------------------------- 5. PT: egen övning i passbyggaren ---
await p.goto(base + "/pt/pass")
await p.waitForSelector("h1:has-text('Passbyggare')")
const before = (await demo()).templates[0].exercises.length
await p.locator("button:has-text('Lägg till egen övning'):visible").first().click()
await dlg.waitFor()
await p.fill("#cx-name", "Kedjeböj mot låda")
await p.fill("#cx-weight", "60")
await dlg.locator("button:has-text('Spara och lägg i passet')").click()
await dlg.waitFor({ state: "detached" })
await p.waitForSelector("text=Kedjeböj mot låda")
await p.locator("button:has-text('Spara'):visible").first().click()
await p.waitForSelector("text=Mallen är sparad")
const d5 = await demo()
const tpl = d5.templates[0]
const slade = d5.exercises.find((e) => e.name === "Kedjeböj mot låda")
check(slade?.custom?.ownerId === "t1", "PT:ns egna övning sparas på PT:n")
check(tpl.exercises.length === before + 1 && tpl.exercises.at(-1).exerciseId === slade.id && tpl.exercises.at(-1).targetKg === 60, "och läggs direkt i passet (60 kg)")
await p.screenshot({ path: `${out}/v19-pt-passbyggare.png`, fullPage: true })

// ----------------------------------------------------- 6. PT:ns länk ---
const fresh = await browser.newContext({ viewport: { width: 390, height: 844 } })
const q = await fresh.newPage()
q.on("pageerror", (e) => errors.push(`${q.url()} pageerror: ${e.message}`))
await q.goto(base + "/ref/EX-8FK29A")
await q.waitForURL("**/kom-igang?ptkod=EX-8FK29A")
await q.waitForSelector("[data-testid=pt-invite-banner]")
check((await q.locator("[data-testid=pt-invite-banner]").innerText()).includes("EX-8FK29A"), "PT:ns länk leder till registreringen med koden")
check((await q.evaluate(() => JSON.parse(localStorage["coavira:ptkod"]).code)) === "EX-8FK29A", "koden sparas tills kontot skapats")
await q.goto(base + "/ref/SARA7KQ2")
await q.waitForURL("**/kom-igang?ref=SARA7KQ2")
ok("vänkoder (v18) fungerar som förut")
await fresh.close()

check(errors.length === 0, `inga sidfel${errors.length ? `: ${errors.join(" | ")}` : ""}`)
await browser.close()
